using System.Collections.Generic;
using RimWorld;
using UnityEngine;
using Verse;
using WhisperOfTheForest.Experimental.Spells;

namespace WhisperOfTheForest.Experimental
{
    /// <summary>Colour role of a <see cref="SpellbookStyle.Button"/>.</summary>
    internal enum SpellbookButtonRole
    {
        /// <summary>Jade: the action the page is for (create, cast).</summary>
        Primary,

        /// <summary>Walnut: harmless page actions (clear the bar, toggles).</summary>
        Secondary,

        /// <summary>Rust: destroys saved data (delete the slot).</summary>
        Danger
    }

    /// <summary>
    /// Palette, keyed strings, textures and the small drawing kit of the spellbook window.
    ///
    /// The decoration textures live in Textures/Experiments/Spellbook/UI and are generated by
    /// Tools/art/gen_spellbook_ui.py. Two kinds: natural-colour pieces (parchment, frames, socket,
    /// inlay, divider, vine) drawn as they are, and white masks (button, panel, ribbon, glow, icons)
    /// tinted with GUI.color so one texture serves every state. "*Atlas" textures follow
    /// <see cref="Widgets.DrawAtlas(Rect, Texture2D)"/>: the corner is a quarter of the width.
    ///
    /// Textures are resolved lazily on the UI thread and cached per path, misses included, so a
    /// missing file is reported once by ContentFinder and then simply not drawn. No text is baked
    /// into an image: every label uses the game font so Chinese stays crisp.
    /// </summary>
    [StaticConstructorOnStartup]
    internal static class SpellbookStyle
    {
        /// <summary>Longest chain the shared tuning def accepts; the book never invents its own limit.</summary>
        public static int MaxGlyphs
        {
            get { return SpellDefs.Tuning.maxGlyphs; }
        }

        // ---------------------------------------------------------------- palette

        // On the dark cover.
        public static readonly Color CoverText = new Color(0.93f, 0.88f, 0.74f, 1f);
        public static readonly Color CoverTextDim = new Color(0.70f, 0.66f, 0.54f, 1f);
        public static readonly Color CoverGold = new Color(0.90f, 0.76f, 0.44f, 1f);
        public static readonly Color CoverWarning = new Color(1f, 0.58f, 0.48f, 1f);

        // On parchment.
        public static readonly Color Ink = new Color(0.17f, 0.13f, 0.08f, 1f);
        public static readonly Color InkDim = new Color(0.36f, 0.30f, 0.21f, 1f);
        public static readonly Color InkFaint = new Color(0.52f, 0.46f, 0.35f, 1f);
        public static readonly Color Good = new Color(0.12f, 0.42f, 0.27f, 1f);
        public static readonly Color Warning = new Color(0.62f, 0.17f, 0.11f, 1f);

        /// <summary>Light text on the inlaid name/search fields.</summary>
        public static readonly Color FieldText = new Color(0.94f, 0.90f, 0.78f, 1f);

        // Roles.
        public static readonly Color Jade = new Color(0.22f, 0.55f, 0.47f, 1f);
        public static readonly Color JadeBright = new Color(0.45f, 0.86f, 0.74f, 1f);
        public static readonly Color Walnut = new Color(0.50f, 0.38f, 0.24f, 1f);
        public static readonly Color Rust = new Color(0.62f, 0.25f, 0.17f, 1f);

        // Bookmark ribbons.
        public static readonly Color RibbonActive = new Color(0.30f, 0.66f, 0.55f, 1f);
        public static readonly Color RibbonUsed = new Color(0.25f, 0.43f, 0.33f, 1f);
        public static readonly Color RibbonEmpty = new Color(0.47f, 0.40f, 0.30f, 1f);

        /// <summary>Alpha of a catalogue rune the current bar cannot take: still readable, visibly off.</summary>
        public const float BlockedAlpha = 0.4f;

        // ---------------------------------------------------------------- textures

        private const string Ui = "Experiments/Spellbook/UI/";
        private const string CoverPath = "Experiments/Spellbook/BookCover";

        private static readonly Dictionary<string, Texture2D> textures = new Dictionary<string, Texture2D>();

        public static Texture2D Cover => Tex(CoverPath);
        public static Texture2D CoverFrameAtlas => Tex(Ui + "CoverFrameAtlas");
        public static Texture2D Parchment => Tex(Ui + "Parchment");
        public static Texture2D PageFrameAtlas => Tex(Ui + "PageFrameAtlas");
        public static Texture2D SpineShade => Tex(Ui + "SpineShade");
        public static Texture2D ButtonAtlas => Tex(Ui + "ButtonAtlas");
        public static Texture2D PanelAtlas => Tex(Ui + "PanelAtlas");
        public static Texture2D InlayAtlas => Tex(Ui + "InlayAtlas");
        public static Texture2D Socket => Tex(Ui + "Socket");
        public static Texture2D Glow => Tex(Ui + "Glow");
        public static Texture2D Ribbon => Tex(Ui + "Ribbon");
        public static Texture2D Divider => Tex(Ui + "Divider");
        public static Texture2D VineTrack => Tex(Ui + "VineTrack");
        public static Texture2D IconOk => Tex(Ui + "IconOk");
        public static Texture2D IconWarn => Tex(Ui + "IconWarn");
        public static Texture2D IconRemove => Tex(Ui + "IconRemove");
        public static Texture2D IconSearch => Tex(Ui + "IconSearch");
        public static Texture2D IconHourglass => Tex(Ui + "IconHourglass");

        /// <summary>Icon for one glyph. The shared def decides the path, so page and runtime agree.</summary>
        public static Texture2D GlyphIcon(SpellGlyphDef glyph)
        {
            return glyph == null ? null : Tex(SpellDefs.IconPathFor(glyph));
        }

        public static Texture2D Tex(string path)
        {
            if (path.NullOrEmpty())
            {
                return null;
            }

            Texture2D texture;
            if (textures.TryGetValue(path, out texture))
            {
                return texture;
            }

            // Shipped with the mod: a miss is a packaging error, reported once and then cached.
            texture = ContentFinder<Texture2D>.Get(path, true);
            textures[path] = texture;
            return texture;
        }

        // ---------------------------------------------------------------- strings

        public static string T(string key)
        {
            return Translator.Translate(key);
        }

        public static string TF(string key, params object[] args)
        {
            return string.Format(Translator.Translate(key), args);
        }

        /// <summary>Ticks as seconds with at most two decimals ("0.75", "1.5", "0").</summary>
        public static string Seconds(int ticks)
        {
            return ((float)ticks / GenTicks.TicksPerRealSecond).ToString("0.##");
        }

        public static string KindLabel(SpellGlyphKind kind)
        {
            switch (kind)
            {
                case SpellGlyphKind.Form:
                    return T("WotF_Spellbook.KindForm");
                case SpellGlyphKind.Effect:
                    return T("WotF_Spellbook.KindEffect");
                case SpellGlyphKind.Trigger:
                    // No trigger rune ships any more; the kind stays because the segment machinery
                    // still recognises one in an old save.
                    return T("WotF_Spellbook.KindTrigger");
                default:
                    return T("WotF_Spellbook.KindAugment");
            }
        }

        /// <summary>Ink colour of a rune kind, readable on parchment.</summary>
        public static Color KindColor(SpellGlyphKind kind)
        {
            switch (kind)
            {
                case SpellGlyphKind.Form:
                    return new Color(0.11f, 0.44f, 0.39f, 1f);
                case SpellGlyphKind.Effect:
                    return new Color(0.64f, 0.31f, 0.09f, 1f);
                case SpellGlyphKind.Augment:
                    return new Color(0.42f, 0.25f, 0.58f, 1f);
                default:
                    return InkFaint;
            }
        }

        // ---------------------------------------------------------------- text

        /// <summary>Single-line label, ellipsed instead of wrapped.</summary>
        public static void DrawLabel(Rect rect, string text, GameFont font, Color color, TextAnchor anchor)
        {
            using (TechLabDrawScope.Begin())
            {
                Text.Font = font;
                Text.Anchor = anchor;
                GUI.color = color;
                Widgets.LabelEllipses(rect, text);
            }
        }

        public static void DrawLabel(Rect rect, string text, GameFont font, Color color)
        {
            DrawLabel(rect, text, font, color, TextAnchor.UpperLeft);
        }

        /// <summary>Wrapped paragraph; also reports the height it actually needs.</summary>
        public static float DrawParagraph(Rect rect, string text, GameFont font, Color color)
        {
            using (TechLabDrawScope.Begin())
            {
                Text.Font = font;
                Text.Anchor = TextAnchor.UpperLeft;
                GUI.color = color;
                float height = Mathf.Min(rect.height, Text.CalcHeight(text, rect.width));
                Widgets.Label(new Rect(rect.x, rect.y, rect.width, height), text);
                return height;
            }
        }

        public static float TextWidth(string text, GameFont font)
        {
            using (TechLabDrawScope.Begin())
            {
                Text.Font = font;
                return Text.CalcSize(text).x;
            }
        }

        // ---------------------------------------------------------------- primitives

        public static void DrawIcon(Rect rect, Texture2D texture, Color tint)
        {
            if (texture == null)
            {
                return;
            }

            Color previous = GUI.color;
            GUI.color = tint;
            GUI.DrawTexture(rect, texture, ScaleMode.ScaleToFit);
            GUI.color = previous;
        }

        public static void DrawStretched(Rect rect, Texture2D texture, Color tint)
        {
            if (texture == null)
            {
                return;
            }

            Color previous = GUI.color;
            GUI.color = tint;
            GUI.DrawTexture(rect, texture, ScaleMode.StretchToFill);
            GUI.color = previous;
        }

        /// <summary>Nine-slice draw through the vanilla atlas routine, tinted.</summary>
        public static void DrawAtlas(Rect rect, Texture2D atlas, Color tint)
        {
            if (atlas == null)
            {
                return;
            }

            Color previous = GUI.color;
            GUI.color = tint;
            Widgets.DrawAtlas(rect, atlas);
            GUI.color = previous;
        }

        /// <summary>Soft round light centred on <paramref name="center"/>.</summary>
        public static void DrawGlow(Vector2 center, float size, Color color, float alpha)
        {
            if (alpha <= 0f)
            {
                return;
            }

            DrawStretched(new Rect(center.x - size * 0.5f, center.y - size * 0.5f, size, size), Glow,
                new Color(color.r, color.g, color.b, color.a * alpha));
        }

        /// <summary>The same colour at a fraction of its alpha, for greyed-out catalogue entries.</summary>
        public static Color Fade(Color color, float alpha)
        {
            return new Color(color.r, color.g, color.b, color.a * alpha);
        }

        public static Color Lighten(Color color, float amount)
        {
            return new Color(Mathf.Lerp(color.r, 1f, amount), Mathf.Lerp(color.g, 1f, amount),
                Mathf.Lerp(color.b, 1f, amount), color.a);
        }

        public static Color Darken(Color color, float amount)
        {
            return new Color(color.r * (1f - amount), color.g * (1f - amount), color.b * (1f - amount), color.a);
        }

        // ---------------------------------------------------------------- book parts

        /// <summary>Green leather filling the window, with the brass frame on top.</summary>
        public static void DrawCover(Rect rect)
        {
            DrawStretched(rect, Cover, Color.white);
            DrawAtlas(rect, CoverFrameAtlas, Color.white);
        }

        /// <summary>
        /// One parchment page: paper, the shadow of the spine on the inner edge and the vine frame.
        /// <paramref name="spineOnRight"/> is true for the left page of the spread.
        /// </summary>
        public static void DrawPage(Rect rect, bool spineOnRight)
        {
            DrawStretched(rect, Parchment, Color.white);

            Texture2D shade = SpineShade;
            if (shade != null)
            {
                const float shadeWidth = 30f;
                Color previous = GUI.color;
                GUI.color = new Color(1f, 1f, 1f, 0.55f);
                if (spineOnRight)
                {
                    // Flipped horizontally: dark at the right edge.
                    GUI.DrawTextureWithTexCoords(new Rect(rect.xMax - shadeWidth, rect.y, shadeWidth, rect.height),
                        shade, new Rect(1f, 0f, -1f, 1f));
                }
                else
                {
                    GUI.DrawTexture(new Rect(rect.x, rect.y, shadeWidth, rect.height), shade, ScaleMode.StretchToFill);
                }

                GUI.color = previous;
            }

            DrawAtlas(rect, PageFrameAtlas, Color.white);
        }

        /// <summary>Centred page title with the leaf divider under it.</summary>
        public static void DrawPageTitle(Rect titleRect, Rect dividerRect, string text)
        {
            DrawLabel(titleRect, text, GameFont.Medium, Ink, TextAnchor.MiddleCenter);
            DrawIcon(dividerRect, Divider, Color.white);
        }

        /// <summary>Tinted card: faint wash, firm outline.</summary>
        public static void DrawPanel(Rect rect, Color tint)
        {
            DrawAtlas(rect, PanelAtlas, tint);
        }

        /// <summary>Small caption on parchment: the kind colour as a dot, then the text.</summary>
        public static void DrawKindTag(Rect rect, SpellGlyphKind kind, float alpha)
        {
            Color color = Fade(KindColor(kind), alpha);
            float dot = 6f;
            Widgets.DrawBoxSolid(new Rect(rect.x, rect.y + (rect.height - dot) * 0.5f, dot, dot), color);
            DrawLabel(new Rect(rect.x + dot + 4f, rect.y, rect.width - dot - 4f, rect.height), KindLabel(kind),
                GameFont.Tiny, color, TextAnchor.MiddleLeft);
        }

        /// <summary>
        /// A rune in its brass socket. A null icon draws the empty socket, recessed into the page;
        /// <paramref name="alpha"/> fades both together.
        /// </summary>
        public static void DrawSocket(Rect rect, Texture2D icon, float alpha)
        {
            DrawIcon(rect, Socket, new Color(1f, 1f, 1f, alpha));
            if (icon != null)
            {
                float inset = rect.width * 0.12f;
                DrawIcon(new Rect(rect.x + inset, rect.y + inset, rect.width - 2f * inset, rect.height - 2f * inset), icon,
                    new Color(1f, 1f, 1f, alpha));
            }
        }

        // ---------------------------------------------------------------- controls

        private static GUIStyle fieldStyle;

        /// <summary>
        /// The game's text-field style without its background, so the text sits on the inlay.
        /// Built on first use because GUIStyle needs the GUI skin, which only exists in OnGUI.
        /// </summary>
        private static GUIStyle FieldStyle
        {
            get
            {
                if (fieldStyle == null)
                {
                    fieldStyle = new GUIStyle(Text.textFieldStyles[1]);
                    GUIStyleState[] states =
                    {
                        fieldStyle.normal, fieldStyle.hover, fieldStyle.focused, fieldStyle.active,
                        fieldStyle.onNormal, fieldStyle.onHover, fieldStyle.onFocused, fieldStyle.onActive
                    };
                    for (int i = 0; i < states.Length; i++)
                    {
                        states[i].background = null;
                        states[i].textColor = FieldText;
                    }
                }

                return fieldStyle;
            }
        }

        /// <summary>
        /// Single-line text field on a dark inlay; the light text and caret stay visible there.
        /// <paramref name="placeholder"/> is shown while the field is empty.
        /// </summary>
        public static string TextField(Rect rect, string text, string placeholder, Texture2D leadingIcon)
        {
            DrawAtlas(rect, InlayAtlas, Color.white);

            Rect inner = new Rect(rect.x + 6f, rect.y, rect.width - 10f, rect.height);
            if (leadingIcon != null)
            {
                float size = Mathf.Min(14f, rect.height - 8f);
                DrawIcon(new Rect(inner.x, rect.y + (rect.height - size) * 0.5f, size, size), leadingIcon,
                    Fade(FieldText, 0.55f));
                inner.xMin += size + 4f;
            }

            if (text.NullOrEmpty() && !placeholder.NullOrEmpty())
            {
                DrawLabel(inner, placeholder, GameFont.Tiny, Fade(FieldText, 0.45f), TextAnchor.MiddleLeft);
            }

            string result;
            using (TechLabDrawScope.Begin())
            {
                Text.Font = GameFont.Small;
                result = GUI.TextField(inner, text ?? "", FieldStyle);
            }

            return result ?? "";
        }

        /// <summary>
        /// Bevelled plaque button. A disabled button is drawn faded and never reports a click,
        /// like <see cref="Widgets.ButtonText(Rect, string, bool, bool, bool, TextAnchor?)"/> with active=false.
        /// </summary>
        public static bool Button(Rect rect, string label, SpellbookButtonRole role, bool enabled)
        {
            Color baseColor = role == SpellbookButtonRole.Primary ? Jade
                : role == SpellbookButtonRole.Danger ? Rust
                : Walnut;

            bool over = enabled && Mouse.IsOver(rect);
            Color tint = baseColor;
            if (!enabled)
            {
                float grey = baseColor.grayscale;
                tint = new Color(grey, grey, grey, 0.45f);
            }
            else if (over)
            {
                tint = Input.GetMouseButton(0) ? Darken(baseColor, 0.15f) : Lighten(baseColor, 0.18f);
            }

            DrawAtlas(rect, ButtonAtlas, tint);
            DrawLabel(rect.ContractedBy(4f, 0f), label, GameFont.Small,
                enabled ? CoverText : Fade(CoverText, 0.55f), TextAnchor.MiddleCenter);

            return enabled && Widgets.ButtonInvisible(rect, true);
        }
    }
}
